require 'json'
require 'fileutils'
require 'time'

class GraphvizCustomBlocksService
  NAME_REGEX = /\A[a-zA-Z_][a-zA-Z0-9_]*\z/

  def self.storage_dir
    if Dir.exist?('/srv/ctlabs-server/recordings')
      '/srv/ctlabs-server/recordings'
    else
      File.expand_path('../../config', __FILE__)
    end
  end

  def self.json_path
    File.join(storage_dir, 'custom_blocks.json')
  end

  def self.rb_path
    File.join(storage_dir, 'custom_blocks.rb')
  end

  def self.all
    path = json_path
    return [] unless File.exist?(path)

    raw = File.read(path, encoding: 'UTF-8')
    data = JSON.parse(raw)
    data.is_a?(Array) ? data : []
  rescue StandardError => e
    warn "[GraphvizCustomBlocksService] Error reading #{json_path}: #{e.message}"
    []
  end

  def self.find(name)
    target = name.to_s.strip
    all.find { |b| b['name'].to_s == target }
  end

  def self.validate_code(code)
    return 'Code cannot be empty' if code.to_s.strip.empty?
    begin
      RubyVM::InstructionSequence.compile(code.to_s)
      nil
    rescue SyntaxError => e
      e.message.sub(/\A\(eval\):\d+:\s*/, '')
    rescue StandardError => e
      e.message
    end
  end

  def self.save(params)
    name = params[:name] || params['name']
    name = name.to_s.strip

    unless name =~ NAME_REGEX
      return { ok: false, error: "Invalid block name '#{name}'. Must start with a letter/underscore and contain only alphanumeric characters and underscores." }
    end

    code = (params[:code] || params['code']).to_s.strip
    if code.empty?
      return { ok: false, error: 'Ruby code cannot be empty.' }
    end

    syntax_err = validate_code(code)
    if syntax_err
      return { ok: false, error: "Syntax error in block code: #{syntax_err}" }
    end

    raw_params = (params[:params] || params['params']).to_s.strip
    snippet = (params[:snippet] || params['snippet']).to_s.strip
    description = (params[:description] || params['description']).to_s.strip

    if snippet.empty?
      snippet = raw_params.empty? ? "<%= #{name} %>" : "<%= #{name}(...) %>"
    end

    blocks = all
    existing_idx = blocks.find_index { |b| b['name'] == name }
    now = Time.now.utc.iso8601

    entry = {
      'name' => name,
      'params' => raw_params,
      'code' => code,
      'snippet' => snippet,
      'description' => description,
      'updated_at' => now
    }

    if existing_idx
      entry['created_at'] = blocks[existing_idx]['created_at'] || now
      blocks[existing_idx] = entry
    else
      entry['created_at'] = now
      blocks << entry
    end

    # Sort alphabetically by name
    blocks.sort_by! { |b| b['name'].to_s.downcase }

    persist!(blocks)
    { ok: true, block: entry, blocks: blocks }
  rescue StandardError => e
    { ok: false, error: "Failed to save block: #{e.message}" }
  end

  def self.delete(name)
    target = name.to_s.strip
    blocks = all
    initial_len = blocks.length
    blocks.reject! { |b| b['name'].to_s == target }

    if blocks.length == initial_len
      return { ok: false, error: "Custom block '#{target}' not found." }
    end

    persist!(blocks)
    { ok: true, blocks: blocks }
  rescue StandardError => e
    { ok: false, error: "Failed to delete block: #{e.message}" }
  end

  def self.all_ruby_code
    blocks = all
    return '' if blocks.empty?

    blocks.map do |b|
      "# Block: #{b['name']}\n#{b['code']}\n"
    end.join("\n")
  end

  def self.load_into(ctx)
    code = all_ruby_code
    return if code.strip.empty?

    ctx.instance_eval(code, rb_path, 1)
  rescue StandardError, SyntaxError => e
    warn "[GraphvizCustomBlocksService] Error loading custom blocks into context: #{e.message}"
  end

  def self.persist!(blocks)
    FileUtils.mkdir_p(storage_dir)

    # 1. Write JSON file
    File.write(json_path, JSON.pretty_generate(blocks), encoding: 'UTF-8')

    # 2. Write human-readable Ruby file
    header = <<~RB
      # -----------------------------------------------------------------------------
      # Global Custom Building Blocks for Graphviz Templates
      # Auto-generated by ctlabs. Do not edit directly unless preserving method signatures.
      # -----------------------------------------------------------------------------

    RB

    rb_content = header + blocks.map { |b| "# Block: #{b['name']}\n#{b['code']}\n" }.join("\n")
    File.write(rb_path, rb_content, encoding: 'UTF-8')
  end
  private_class_method :persist!
end
